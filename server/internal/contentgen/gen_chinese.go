// shuffleStr 打乱字符串切片（固定种子，确定性输出）。
func shuffleStr(a []string) []string {
	rng := rand.New(rand.NewSource(int64(len(a)*131 + 7)))
	out := append([]string{}, a...)
	rng.Shuffle(len(out), func(i, j int) { out[i], out[j] = out[j], out[i] })
	return out
}

